"""Prepare an isolated relation-agnostic HiRAG workspace from a Multi workspace.

This is a deterministic conversion utility.  It never calls an LLM, embedding
model, reranker, or mutates the source workspace.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import sys
from pathlib import Path

import networkx as nx

PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from hirag._op import build_single_graph_from_multi_graph
from hirag._storage import NetworkXSingleStorage


GRAPH_NAME = "graph_chunk_entity_relation.graphml"
AUDIT_NAME = "single_graph_edge_audit.jsonl"
MANIFEST_NAME = "single_graph_manifest.json"
SAFE_REUSED_ASSETS = (
    "kv_store_full_docs.json",
    "kv_store_text_chunks.json",
    "vdb_chunks.json",
    "vdb_entities.json",
)


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-workspace", required=True, type=Path)
    parser.add_argument("--target-workspace", required=True, type=Path)
    parser.add_argument(
        "--force",
        action="store_true",
        help="Replace only files generated by this preparation script in target.",
    )
    parser.add_argument(
        "--skip-safe-assets",
        action="store_true",
        help="Do not copy documents, text chunks, and the entity vector store.",
    )
    return parser.parse_args()


def ensure_safe_target(target: Path, force: bool) -> None:
    target.mkdir(parents=True, exist_ok=True)
    generated = {GRAPH_NAME, AUDIT_NAME, MANIFEST_NAME}
    existing = {path.name for path in target.iterdir()}
    blocked = existing - generated
    if blocked:
        raise RuntimeError(
            f"Target workspace is not empty: {target}. Refusing to mix files: {sorted(blocked)}"
        )
    if not force and existing & generated:
        raise RuntimeError(
            "Target already contains a prepared Single graph. Use --force to replace it."
        )


def main() -> None:
    args = parse_args()
    source = args.source_workspace.resolve()
    target = args.target_workspace.resolve()
    source_graph_path = source / GRAPH_NAME
    if not source_graph_path.exists():
        raise FileNotFoundError(f"Multi graph not found: {source_graph_path}")
    if source == target:
        raise ValueError("Source and target workspaces must be different.")

    ensure_safe_target(target, args.force)
    source_graph = nx.read_graphml(source_graph_path)
    if not source_graph.is_multigraph():
        raise ValueError(
            f"Source graph is already single-edge, not a MultiGraph: {source_graph_path}"
        )

    single_graph, audit_rows = build_single_graph_from_multi_graph(source_graph)
    target_graph_path = target / GRAPH_NAME
    NetworkXSingleStorage.write_nx_graph(single_graph, str(target_graph_path))

    with (target / AUDIT_NAME).open("w", encoding="utf-8") as handle:
        for row in audit_rows:
            handle.write(json.dumps(row, ensure_ascii=False) + "\n")

    copied_assets: list[str] = []
    if not args.skip_safe_assets:
        for asset_name in SAFE_REUSED_ASSETS:
            source_asset = source / asset_name
            if source_asset.exists():
                shutil.copy2(source_asset, target / asset_name)
                copied_assets.append(asset_name)

    parallel_pairs = sum(row["multi_edge_count"] > 1 for row in audit_rows)
    manifest = {
        "conversion": "multi_to_single_relation_agnostic_projection",
        "source_workspace": str(source),
        "target_workspace": str(target),
        "source_graph_sha256": sha256(source_graph_path),
        "target_graph_sha256": sha256(target_graph_path),
        "source_nodes": source_graph.number_of_nodes(),
        "source_multi_edges": source_graph.number_of_edges(),
        "target_single_edges": single_graph.number_of_edges(),
        "parallel_entity_pairs_merged": parallel_pairs,
        "copied_safe_assets": copied_assets,
        "not_copied": [
            "kv_store_llm_response_cache.json",
            "kv_store_community_reports.json",
            "rgcn_data.pt",
            "rgcn_embeddings.pt",
            "rgcn_data_mapping.json",
            "rgcn_embeddings_mapping.json",
        ],
    }
    with (target / MANIFEST_NAME).open("w", encoding="utf-8") as handle:
        json.dump(manifest, handle, ensure_ascii=False, indent=2)
        handle.write("\n")

    print(json.dumps(manifest, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
